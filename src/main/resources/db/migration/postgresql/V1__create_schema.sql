CREATE TABLE users
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name  VARCHAR(100) NOT NULL,
    username   VARCHAR(150) NOT NULL UNIQUE,
    password   VARCHAR(255) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE training_types
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE trainees
(
    id              BIGINT PRIMARY KEY,
    date_of_birth   DATE,
    city            VARCHAR(120),
    street          VARCHAR(150),
    building_number INTEGER,
    zipcode         VARCHAR(20),
    CONSTRAINT fk_trainees_users FOREIGN KEY (id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_trainees_building_number CHECK (building_number IS NULL OR building_number > 0)
);

CREATE TABLE trainers
(
    id                BIGINT PRIMARY KEY,
    specialization_id BIGINT NOT NULL,
    CONSTRAINT fk_trainers_users FOREIGN KEY (id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_trainers_specialization FOREIGN KEY (specialization_id) REFERENCES training_types (id)
);

CREATE TABLE trainee_trainers
(
    trainee_id BIGINT NOT NULL,
    trainer_id BIGINT NOT NULL,
    PRIMARY KEY (trainee_id, trainer_id),
    CONSTRAINT fk_assignment_trainee FOREIGN KEY (trainee_id) REFERENCES trainees (id) ON DELETE CASCADE,
    CONSTRAINT fk_assignment_trainer FOREIGN KEY (trainer_id) REFERENCES trainers (id) ON DELETE CASCADE
);

CREATE TABLE trainings
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainee_id       BIGINT       NOT NULL,
    trainer_id       BIGINT       NOT NULL,
    name             VARCHAR(200) NOT NULL,
    training_type_id BIGINT       NOT NULL,
    training_date    DATE         NOT NULL,
    duration_minutes INTEGER      NOT NULL,
    CONSTRAINT fk_trainings_trainee FOREIGN KEY (trainee_id) REFERENCES trainees (id) ON DELETE CASCADE,
    CONSTRAINT fk_trainings_trainer FOREIGN KEY (trainer_id) REFERENCES trainers (id),
    CONSTRAINT fk_trainings_type FOREIGN KEY (training_type_id) REFERENCES training_types (id),
    CONSTRAINT ck_training_duration CHECK (duration_minutes > 0),
    CONSTRAINT ck_training_name CHECK (LENGTH(TRIM(name)) > 0)
);

CREATE INDEX idx_trainings_trainee_date ON trainings (trainee_id, training_date);
CREATE INDEX idx_trainings_trainer_date ON trainings (trainer_id, training_date);
CREATE INDEX idx_trainings_type ON trainings (training_type_id);
CREATE INDEX idx_trainee_trainers_trainer ON trainee_trainers (trainer_id);
CREATE INDEX idx_trainers_specialization ON trainers (specialization_id);
